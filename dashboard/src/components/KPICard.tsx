import React from 'react';
import Link from 'next/link';

/**
 * Type safety definition for Dashboard Statistic Card
 */
export interface KPICardProps {
  title: string;
  value: string | number;
  trendText: string;
  trendIcon: string;
  colorVariant: 'primary' | 'secondary' | 'error' | 'tertiary';
  progressPercentage: number;
  href?: string;
}

export const KPICard: React.FC<KPICardProps> = ({ 
  title, 
  value, 
  trendText, 
  trendIcon, 
  colorVariant, 
  progressPercentage,
  href
}) => {
  // Map our dynamic color variants to the custom Tailwind themes generated by Stitch
  const variantMap = {
    primary: {
      border: 'border-primary/10',
      bgText: 'text-primary bg-primary/10',
      fill: 'bg-primary',
    },
    secondary: {
      border: 'border-secondary/10',
      bgText: 'text-secondary bg-secondary/10',
      fill: 'bg-secondary',
    },
    error: {
      border: 'border-error/10',
      bgText: 'text-error bg-error/10',
      fill: 'bg-error',
    },
    tertiary: {
      border: 'border-tertiary/10',
      bgText: 'text-tertiary bg-tertiary/10',
      fill: 'bg-tertiary',
    }
  };

  const theme = variantMap[colorVariant];

  const cardContent = (
    <div className={`bg-surface-container rounded-2xl p-6 glow-active border ${theme.border} transition-all duration-300 hover:scale-[1.02] ${href ? 'cursor-pointer hover:shadow-2xl hover:shadow-' + colorVariant + '/20' : ''}`}>
      <div className="flex justify-between items-start mb-4">
        <div className={`p-2 rounded-lg ${theme.bgText}`}>
          <span className="material-symbols-outlined">{trendIcon}</span>
        </div>
        <span className={`text-[10px] font-mono font-bold px-2 py-0.5 rounded ${theme.bgText}`}>
          {trendText}
        </span>
      </div>
      <p className="text-on-surface-variant font-technical text-xs uppercase tracking-widest">{title}</p>
      <h3 className="text-3xl font-black font-headline mt-1">{value}</h3>
      <div className="mt-4 h-1 w-full bg-surface-container-low rounded-full overflow-hidden">
        <div className={`h-full ${theme.fill} rounded-full`} style={{ width: `${progressPercentage}%` }}></div>
      </div>
    </div>
  );

  if (href) {
    return <Link href={href} className="block w-full">{cardContent}</Link>;
  }

  return cardContent;
};
